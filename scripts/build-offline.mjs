const loadingAssets = {
  'assets/loading-orbit.gif': 'image/gif',
  'assets/loading-orbit-still.svg': 'image/svg+xml',
};
for (const [asset, mime] of Object.entries(loadingAssets)) {
  const uri = `data:${mime};base64,${(await readFile(path.join(source, asset))).toString('base64')}`;
  html = html.replaceAll(asset, uri);
}
if (/<\/style/i.test(css)) throw new Error('Unexpected style end tag');
html = html.replace('href="favicon.svg"', `href="${favicon}"`)
  .replace('<link rel="stylesheet" href="style.css">', `<style>\n${css}\n</style>`)
