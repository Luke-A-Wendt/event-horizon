import assert from 'node:assert/strict';
import { fixture } from './render-fixture.mjs';
import { CpuRenderer, cpuProject, cpuSpectrum } from '../dist/cpu-renderer.js';

const frame={observer:[0,0,10],forward:[0,0,-1],right:[1,0,0],up:[0,1,0]};
assert.equal(cpuProject([0,0,11],frame,640,400),null,'points behind camera are clipped');
assert.deepEqual([cpuProject([0,0,0],frame,640,400).x,cpuProject([0,0,0],frame,640,400).y],[320,200]);
assert.ok(cpuProject([1,0,0],frame,640,400).x>320,'right direction projects right');
assert.ok(cpuProject([0,1,0],frame,640,400).y<200,'up direction projects up');
assert.ok(cpuSpectrum([1,1,1],'xray','hot')[2]>cpuSpectrum([1,1,1],'xray','surface')[2]*10,'CPU bands distinguish hot gas from cool material');
const f=fixture({width:2000,height:1200});let paints=0,contexts=[];
const gradient={addColorStop(){}};
const context=new Proxy({fillRect(){paints++;},createRadialGradient(){return gradient;}},{get:(o,k)=>k in o?o[k]:(()=>{})});
f.canvas.getContext=type=>{contexts.push(type);return type==='2d'?context:null;};
let stats;const renderer=new CpuRenderer(f.canvas,{onStats:s=>stats=s});
assert.deepEqual(contexts,['2d'],'CPU fallback never starts any GPU context');
assert.ok(f.canvas.width<=640&&f.canvas.height<=420,'old-device pixel cap');
assert.ok(renderer.ready&&renderer.getState().cpu);
let rendered=0;const originalRender=renderer.render.bind(renderer);renderer.render=(...args)=>{const done=originalRender(...args);if(done)rendered++;return done;};
for(let n=0;n<=120;n++)f.step(renderer,n*1000/60);
assert.ok(rendered>=59&&rendered<=62,'CPU draw budget is 30Hz on a 60Hz display');
assert.ok(paints>0);assert.equal(f.draws,0);assert.equal(stats.webgl,0);assert.equal(stats.cpu,true);
const ship=renderer.addObject('enterprise',12,.5,1);renderer.focusObject(ship.id,'track');renderer.render(3000);
assert.ok(renderer.getState().cameraDistanceMeters<10000,'close view preserves physical craft dimensions');
renderer.update({grid:true,jets:true,planet:true,nebula:true});renderer.render(3050);
renderer.setPresentationPaused(true);const before=paints;assert.equal(renderer.render(3100),false);assert.equal(paints,before);
renderer.setPresentationPaused(false);assert.ok((await renderer.captureImage()).size>0);
assert.equal((await renderer.getVRSupport()).supported,false);
await assert.rejects(renderer.enterVR(),/GPU/);
renderer.dispose();assert.equal(renderer.render(3200),false);
console.log('CPU fallback: bounded rendering, spectra, camera projection, physical objects, capture, and GPU isolation passed.');
