import assert from 'node:assert/strict';
import {BlackHoleRenderer} from '../dist/renderer.js';
import {formatGravity} from '../dist/pilot-ui.js';
import {serializeScene,parseScene} from '../dist/scene-file.js';
import {fixture} from './render-fixture.mjs';
const r=new BlackHoleRenderer(fixture().canvas,{autoStart:false,bindControls:false,deferProgram:true});
for(const [value,expected] of [[0,'0.0g'],[1,'1.0g'],[.83,'0.8g'],[.00023,'0.0g'],[-.87,'0.9g']])assert.equal(formatGravity(value),expected);
r.loadScene('disk');const astronaut=r.addObject('astronaut');
r.fillHoles();r.fillObjects();const initial=r.getOrbitEditInfo(astronaut.id);assert(r.getObjectClock(astronaut.id).accelerationG<=1+1e-9);
const close=initial.radiusMeters*.8;assert(close>initial.minimumMeters);
assert.equal(r.setOrbitRadiusMeters(astronaut.id,close).radiusMeters,close);
r.refreshConfiguration();assert.equal(r.getOrbitEditInfo(astronaut.id).radiusMeters,close);
assert(r.getObjectClock(astronaut.id).accelerationG>1);
assert(r.setOrbitRadiusMeters(astronaut.id,1).radiusMeters>=initial.minimumMeters);
r.loadScene('shuttle-space');const craft=r.objects.find(o=>o.type==='shuttle');
r.setNavigationMode(craft.id,'manual');const full=r.setFlightPower(10);assert.equal(full.thrustSetting,1);assert.equal(full.maxThrustG,1);assert.equal(r.setFlightPower(.26).thrustSetting,.3);
const saved=serializeScene(r);assert.equal(parseScene(saved).objects.find(o=>o.id===craft.id).flight.thrust,.3);
craft.flight.thrust=10;const legacy=serializeScene(r);assert.equal(parseScene(legacy).objects.find(o=>o.id===craft.id).flight.thrust,1);
r.dispose();console.log('PASS: safe default, explicit high-g circular orbit retained, exterior floor, 1 g propulsion ceiling and 0.1 g commands');
