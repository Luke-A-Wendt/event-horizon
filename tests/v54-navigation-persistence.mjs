import assert from 'node:assert/strict';
import {BlackHoleRenderer} from '../dist/renderer.js';
import {snapshotRenderer,restoreRenderer} from '../dist/render-state.js';
import {serializeScene,parseScene,SceneFileError} from '../dist/scene-file.js';
import {fixture} from './render-fixture.mjs';

const create=()=>new BlackHoleRenderer(fixture().canvas,{autoStart:false,bindControls:false,deferProgram:true});
const route=(craftId,nodes,patch={})=>({craftId,nodes,loop:true,active:true,index:1,waitSeconds:.4,inFlight:true,legsCompleted:3,error:'',advanceCount:2,...patch});
const source=create(),restored=create();
try{
 source.loadScene('solar-system');
 const ship=source.objects.find(o=>o.type==='shuttle'),earth=source.objects.find(o=>o.name==='Earth'),moon=source.objects.find(o=>o.name==='Moon'),mars=source.objects.find(o=>o.name==='Mars');
 assert(ship&&earth&&moon&&mars);
 source.navigationModes={[ship.id]:'auto'};
 source.flightSequences={[ship.id]:route(ship.id,[{targetId:earth.id,kind:'orbit'},{targetId:moon.id,kind:'orbit',heading:180},{targetId:mars.id}])};
 source.parkedCamera={craftId:ship.id,parentId:earth.id};
 const original=snapshotRenderer(source),text=serializeScene(source),saved=parseScene(text);
 assert.equal(saved.flightSequences[ship.id].active,false);
 assert.equal(saved.flightSequences[ship.id].inFlight,false);
 assert.equal(saved.flightSequences[ship.id].holding,false);
 assert.equal(saved.flightSequences[ship.id].orbitWait,null);
 assert.equal(saved.flightSequences[ship.id].resumeOnPlay,true);
 assert.equal(saved.flightSequences[ship.id].index,1);
 assert.equal(saved.flightSequences[ship.id].legsCompleted,3);
 assert.deepEqual(saved.flightSequences[ship.id].nodes,source.flightSequences[ship.id].nodes);
 assert.equal(saved.navigationModes[ship.id],'auto');
 assert.equal(saved.transfer,null);assert.equal(saved.autopilot,null);assert.equal(saved.parkedCamera,null);
 assert.deepEqual(snapshotRenderer(source),original,'Saving a paused route never mutates the live flight');
 restoreRenderer(restored,saved);
 assert.deepEqual(restored.objects.find(o=>o.id===ship.id),ship,'The current spacecraft pose and clock survive loading');
 assert(restored.validateFrameGeometry());
 // A pose-only packet transports controls without rebuilding the catalog.
 restoreRenderer(restored,original);const catalog=restored.objects,metadata=restored.orbitGeometryById;
 source.navigationModes[ship.id]='manual';source.flightSequences[ship.id].active=false;
 const delta=snapshotRenderer(source,{includeObjects:false,objectIds:[ship.id]});
 assert(!Object.hasOwn(delta,'objects'));restoreRenderer(restored,delta);
 assert.strictEqual(restored.objects,catalog);assert.strictEqual(restored.orbitGeometryById,metadata);
 assert.equal(restored.navigationModes[ship.id],'manual');assert.equal(restored.flightSequences[ship.id].active,false);
 assert.deepEqual(delta.parkedCamera,source.parkedCamera,'Camera guidance is included for worker reconstruction');
 assert(JSON.stringify(delta).length<JSON.stringify(original).length*.1,'Navigation transport retains the small-packet performance path');
 const bad=(mutate,pattern=SceneFileError)=>{const before=snapshotRenderer(source);mutate();assert.throws(()=>serializeScene(source),pattern);restoreRenderer(source,before);};
 bad(()=>source.navigationModes[ship.id]='broken',/not a supported value/);
 bad(()=>source.navigationModes['stale-craft']='auto',/Shuttle or Enterprise/);
 bad(()=>source.flightSequences[ship.id].nodes=[{targetId:'stale-target'}],/orbitable body/);
 bad(()=>source.flightSequences[ship.id].nodes=[{targetId:ship.id}],/own vehicle/);
 bad(()=>source.flightSequences[ship.id].nodes=[{targetId:'space'}],/orbitable body/);
 bad(()=>source.flightSequences[ship.id].nodes=[{targetId:'bridge-throat'}],/bridge's traveler/);
 bad(()=>source.flightSequences[ship.id].nodes=Array.from({length:65},()=>({targetId:moon.id})),/64 stops/);
 bad(()=>source.flightSequences[ship.id].nodes=[{targetId:moon.id,heading:361}],/finite number/);
 bad(()=>source.flightSequences[ship.id].nodes=[{targetId:moon.id,warpFactor:10}],/finite number/);
 bad(()=>source.flightSequences[ship.id].index=1.5,/integer/);
 bad(()=>source.flightSequences[ship.id].nodes=[{targetId:moon.id,kind:'teleport'}],/not a supported value/);
 const alias=text.replace(`targetId: "${moon.id}"`,'targetId: *unsafe');assert.throws(()=>parseScene(alias),SceneFileError);
 const injected=text.replace('heading: 180','heading: 180\n          object: "not accepted"');assert.throws(()=>parseScene(injected),SceneFileError);
 assert(source.setFlightSequence(ship.id,[{targetId:mars.id}],{loop:false}));assert(source.startFlightSequence(ship.id));source.advanceTravel(2.9);
 const movingCraft=structuredClone(source.objects.find(o=>o.id===ship.id)),movingSaved=parseScene(serializeScene(source));
 assert.equal(movingSaved.transfer,null);assert.equal(movingSaved.flightSequences[ship.id].active,false);assert.deepEqual(movingSaved.objects.find(o=>o.id===ship.id),movingCraft,'Saving midflight keeps the exact pose, velocity, power and clocks without auto-resuming its old curve');
 source.loadScene('bridge');const enterprise=source.objects.find(o=>o.type==='enterprise');
 source.navigationModes={[enterprise.id]:'auto'};
 source.flightSequences={[enterprise.id]:route(enterprise.id,[{targetId:'bridge-throat',kind:'waypoint',heading:0},{targetId:'bridge-far-world',kind:'orbit',warpFactor:1},{targetId:'bridge-near-world'}])};
 source.bridgeParking={[enterprise.id]:{targetId:'bridge-throat',phase:0,heading:180}};
 const bridge=parseScene(serializeScene(source));
 assert.equal(bridge.objects.length,1,'Waypoints are route labels, not injected massive bodies');
 assert.deepEqual(bridge.bridgeParking,source.bridgeParking);
 assert.equal(bridge.flightSequences[enterprise.id].nodes[0].targetId,'bridge-throat');
 bad(()=>source.bridgeParking[enterprise.id].phase=4,/finite number/);
 assert(source.setFlightSequence(enterprise.id,[{targetId:'bridge-throat'},{targetId:'bridge-far-world'}],{loop:false}));assert(source.startFlightSequence(enterprise.id));
 for(let phase=0;phase<10;phase++){source.advanceTravel(6);const phaseSave=parseScene(serializeScene(source));assert.equal(phaseSave.transfer,null);if(!source.state.warp)assert.equal(phaseSave.warpObjectId,null,'Zero-speed bridge stages never retain a stale warp owner');}
 source.loadScene('empty-space');assert.deepEqual(source.navigationModes,{});assert.deepEqual(source.flightSequences,{});assert.deepEqual(source.bridgeParking,{});assert.equal(source.parkedCamera,null);
 const next=snapshotRenderer(source);for(const field of ['navigationModes','flightSequences','bridgeParking','parkedCamera'])delete next[field];
 restored.navigationModes={stale:'manual'};restored.flightSequences={stale:{}};restored.bridgeParking={stale:{}};restored.parkedCamera={craftId:'stale'};
 restoreRenderer(restored,next);assert.deepEqual(restored.navigationModes,{});assert.deepEqual(restored.flightSequences,{});assert.deepEqual(restored.bridgeParking,{});assert.equal(restored.parkedCamera,null);
 console.log('PASS: readable route/mode/bridge-waypoint persistence; paused route restore at saved pose; strict malformed/stale route rejection; bounded worker packet/catalog identity; scene reset isolation.');
}finally{source.dispose();restored.dispose();}
