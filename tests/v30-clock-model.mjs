import './fixtures/shuttle-bridge.mjs';
import assert from 'node:assert/strict';
import {clockRate,CLOCK_LIGHT_SPEED as c,CLOCK_SOLAR_GM as gm} from '../dist/object-clocks.js';
import {fixture} from './render-fixture.mjs';
import {BlackHoleRenderer} from '../dist/renderer.js';

const horizon=2*gm/(c*c),source={id:'hole',massSolar:1,horizonMeters:horizon,positionMeters:[0,0,0]};
const at=radius=>clockRate({positionMeters:[radius*horizon,0,0],sources:[source]});
assert(Math.abs(at(1.125).rateFactor-3)<1e-12);
assert(at(1.000001).rateFactor>999);
assert(Number.isFinite(at(1).rateFactor)&&at(1).rateFactor>999);
assert.equal(clockRate().rateFactor,1);
const r=new BlackHoleRenderer(fixture().canvas,{autoStart:false,bindControls:false});
r.loadScene('test-shuttle-bridge');
const id=r.bridgeObjectId,object=r.objectById.get(id),t=Math.PI/.24;
r.time=t;r.fillObjects();
const reading=r.getObjectClock(id),b=r.configCache.bridgeRadius;
const beta=reading.speedMetersPerSecond/c;
assert(reading.ultrastaticBridge);assert.equal(reading.gravityLossRate,0);
assert(beta>0&&beta<1);assert(Math.abs(reading.rateFactor-1/Math.sqrt(1-beta*beta))<1e-14,'Bridge motion has SR dilation and no gravitational loss');
r.update({bridgeTravel:false});assert.equal(r.getObjectClock(id).rateFactor,reading.rateFactor,'Holding the bridge journey preserves the parking orbit’s clock rate');
r.loadScene('bridge');assert.equal(r.getObjectClock(r.bridgeObjectId).rateFactor,1,'Protected warp clock in the bridge');
r.dispose();
console.log('PASS: near-horizon growth, finite 3× at 1.125rs, ultrastatic bridge with kinematic dilation only, protected warp clock.');
